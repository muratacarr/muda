from typing import Any

from pydantic import BaseModel, ConfigDict


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True)


class TokenUsage(_Frozen):
    """Provider-reported usage. None means the provider did not report it (unknown, not zero)."""

    input_tokens: int | None = None
    output_tokens: int | None = None
    cache_hit_tokens: int | None = None
    cache_miss_tokens: int | None = None


class AIChangeRequest(_Frozen):
    prompt: str  # untrusted user text
    site_summary: str  # trusted, generated by the application from stored content


class AIChangeResult(_Frozen):
    payload: dict[str, Any]  # untrusted; must still pass parse_operation()
    usage: TokenUsage
    model: str
    latency_ms: int
